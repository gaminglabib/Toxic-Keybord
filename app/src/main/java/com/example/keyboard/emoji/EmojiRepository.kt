    fun getRecentEmojis(context: Context): List<String> {
        val prefs = getPrefs(context)
        val raw = prefs.getString(KEY_RECENTS, null) ?: return defaultRecents()
        val items = raw.split(",").filter { it.isNotBlank() }
        return items.ifEmpty { defaultRecents() }
    }

    fun recordEmojiUsage(context: Context, emoji: String) {
        val prefs = getPrefs(context)
        val current = getRecentEmojis(context).toMutableList()
        current.remove(emoji)
        current.add(0, emoji)
        val updated = current.take(MAX_RECENTS).joinToString(",")
        prefs.edit().putString(KEY_RECENTS, updated).apply()
    }

    private fun defaultRecents(): List<String> {
        return listOf("💚", "🔥", "😂", "👍", "❤️", "✨", "😊", "🙏", "😎", "⚡", "🚀", "🇧🇩")
    }

    private fun getPrefs(context: Context): SharedPreferences {
        return context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
    }
